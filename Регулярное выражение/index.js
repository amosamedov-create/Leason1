// Квантифакторы (количество)
/**
 * + - один и больше
 * * - ноль и больше
 * ? - ноль или один
 * {3} - ровно 3
 * {2 ,5} - от 2 до 5 
 * {2, } - 2  и больше 
 */


//  якоря
// ^ - начало строки
// $ - конец строки

// Группа и альтернация 
/**
 * (...) - группа
 * |  - или
 * [abc] - любой из символов a,b,c
 * [^abc] - любой кроме a,b,c
 * [a-z]  - диапазон
 */

console.log(/\d+/.test("123")); //true
console.log(/\d+/.test("Амиру 16 лет")); // true
console.log(/\W+/.test("Амиру 16 лет")); // true
console.log(/\s+/.test("Амиру 16 лет")); // true

const email =  /^[\w.-]+@[\w.-]+\w{2,}$/


console.log(email.test("amirov@mail.ru"));

const phoneNumber = /^\+?\d{11}$/;
console.log(phoneNumber.test("+79287329060"));


const language = /^[А-Яа-я]/
console.log(language.test("ЗДРАСТВУЙТЕ"));

